// Export the two member-facing Session panels, verbatim, for a content-fidelity audit.
//
//   node --experimental-strip-types scripts/export-session-content.mjs
//
// REQUESTED BY COWORK (2026-08-16) to diff the live app text against Greg's twelve Science Check documents —
// "I'm diffing wording, not gist." So this GENERATES from the live modules rather than transcribing them: a
// hand-copied export is a second source that can drift from the app silently, which is the whole failure mode
// this audit exists to catch.
//
// Two panels, per Session:
//   1. "Why it matters"      — lib/content/summaries.ts   (short = collapsed, full = expanded)
//   2. "Explore the Science" — lib/content/explore.ts     (lede + numbered points)
//
// BRANCHES ARE LABELLED, not flattened. Reconnect is one continuous arc carrying three Science Checks (r1/r2/r3)
// and resolves its panel by BEAT, not by session — so a reader diffing "the R2 panel" needs to know which beats
// actually show it. Every stage→asset mapping is printed.

import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { execFileSync } from 'node:child_process';
import { ASSET_SUMMARIES, PHASE_SUMMARIES } from '../lib/content/summaries.ts';
import { ASSET_EXPLORE } from '../lib/content/explore.ts';

const OUT = 'docs/canon/exports/session-content.md';
const commit = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
const version = /APP_VERSION = '([^']+)'/.exec(
  execFileSync('cat', ['lib/version.ts'], { encoding: 'utf8' }),
)?.[1] ?? 'unknown';

const ASSETS = ['r1', 'r2', 'r3', 'w1', 'w2', 'w3', 'b1', 'b2', 'b3', 'c1', 'c2', 'c3'];
const TITLE = {
  r1: 'R1 · Identity Distance Questionnaire', r2: 'R2 · The Fade Doors Exercise',
  r3: 'R3 · The Drift Quiz and Legacy Letter', w1: 'W1 · Disinformation Audit',
  w2: 'W2 · Visualization Workshop', w3: 'W3 · Mindful Monitoring',
  b1: 'B1 · What is Your Why', b2: 'B2 · Appreciating Strengths and Weaknesses',
  b3: 'B3 · Monitoring Health Decisions', c1: 'C1 · Looking Forward',
  c2: 'C2 · The Bigger World Audit', c3: 'C3 · Quality Days',
};
const PHASE_OF = { r: 'reconnect', w: 'rewire', b: 'rebuild', c: 'reclaim' };
// From RECONNECT_STAGE_EXPLORE in explore.ts — kept here only to REPORT the branching to the reader.
const RECONNECT_BEATS = {
  r1: ['entry', 'doors'], r2: ['drift'], r3: ['measurement', 'window', 'checkpoint', 'ceremony'],
};

const L = [];
L.push('# G4L — Session content export (verbatim)');
L.push('');
L.push(`**Stamp:** \`${version} · app @ ${commit}\``);
L.push('');
L.push('Generated by `scripts/export-session-content.mjs` directly from the live modules — not transcribed.');
L.push('Every string below is exactly what the app renders. Re-run the script to refresh.');
L.push('');
L.push('Two panels per Session:');
L.push('');
L.push('- **Why it matters** — `lib/content/summaries.ts`. Renders in two states: `short` is what a member sees');
L.push('  collapsed; `full` is what appears when they expand it. Both are given.');
L.push('- **Explore the Science** — `lib/content/explore.ts`. A lede plus numbered points, in render order.');
L.push('');
L.push('**Branching (the one conditional case).** Nine Sessions map 1:1 to an asset. **Reconnect does not** — it is');
L.push('one continuous arc carrying three Science Checks, and it resolves its Explore panel by BEAT. The beats that');
L.push('show each panel are listed under R1/R2/R3 below. A member inside Reconnect therefore sees R1, then R2, then');
L.push('R3 as they progress — the three are never all visible at once.');
L.push('');
L.push('Phase-level summaries are at the end.');
L.push('');
L.push('---');

for (const id of ASSETS) {
  const s = ASSET_SUMMARIES[id];
  const e = ASSET_EXPLORE[id];
  L.push('');
  L.push(`## ${TITLE[id]}`);
  L.push('');
  L.push(`Phase: ${PHASE_OF[id[0]]}`);
  if (RECONNECT_BEATS[id]) {
    L.push('');
    L.push(`**Shown during these Reconnect beats:** ${RECONNECT_BEATS[id].join(', ')}`);
  }
  L.push('');
  L.push('### Panel 1 — Why it matters');
  L.push('');
  L.push('**Collapsed (`short`):**');
  L.push('');
  L.push(`> ${s.short}`);
  L.push('');
  L.push('**Expanded (`full`):**');
  L.push('');
  L.push(`> ${s.full}`);
  L.push('');
  L.push('### Panel 2 — Explore the Science');
  L.push('');
  if (!e) {
    L.push('_No Explore panel for this Session._');
    L.push('');
    continue;
  }
  L.push('**Lede:**');
  L.push('');
  L.push(`> ${e.lede}`);
  L.push('');
  L.push(`**Points (${e.points.length}, in render order):**`);
  L.push('');
  e.points.forEach((p, i) => {
    L.push(`${i + 1}. **${p.head}**`);
    L.push('');
    L.push(`   ${p.body}`);
    L.push('');
  });
}

L.push('---');
L.push('');
L.push('## Phase summaries');
L.push('');
L.push('Shown at phase entry and on the Program page — not per-Session, included for completeness.');
L.push('');
for (const [key, s] of Object.entries(PHASE_SUMMARIES)) {
  L.push(`### ${key}`);
  L.push('');
  L.push(`**Collapsed:** ${s.short}`);
  L.push('');
  L.push(`**Expanded:** ${s.full}`);
  L.push('');
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, L.join('\n'));

const points = ASSETS.reduce((n, id) => n + (ASSET_EXPLORE[id]?.points.length ?? 0), 0);
const missing = ASSETS.filter((id) => !ASSET_EXPLORE[id]);
console.log(`${OUT}`);
console.log(`  ${ASSETS.length} Sessions · ${points} Explore points · ${Object.keys(PHASE_SUMMARIES).length} phase summaries`);
console.log(`  stamp: ${version} · app @ ${commit}`);
if (missing.length) console.log(`  ! no Explore panel: ${missing.join(', ')}`);
