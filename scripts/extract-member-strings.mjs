// Member-facing string inventory — for the terminology sweep (so it's exhaustive, not walk-by-walk).
// Walks the member-facing source, pulls quoted string literals + JSX text nodes, filters out code/classNames/paths,
// dedups, and writes a traceable list (file:line — string) to docs/member-facing-strings.txt.
// Run: node scripts/extract-member-strings.mjs   ·   re-run any time after a copy change.
//
// Heuristic, not perfect: it errs toward INCLUDING (better a little noise than a missed member string). The file:line
// refs let you filter fast. It does NOT read the DB or the model — only source copy.

import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';

const ROOT = process.cwd();
// Where member copy lives. Excludes tests, scripts, db/migrations, auth (mostly non-copy).
const INCLUDE = ['app', 'lib/content', 'lib/agent', 'lib/ceremony', 'lib/curriculum', 'lib/reclaim', 'lib/rebuild',
  'lib/grinta', 'lib/dashboard', 'lib/beats', 'lib/outreach', 'lib/idq', 'lib/practice', 'lib/measure', 'lib/momentum',
  'lib/commitments', 'lib/connect'];
// Skip internal/non-member surfaces (admin console, API routes, founder agent) + build/test dirs.
const SKIP_DIR = new Set(['node_modules', '.next', '.git', 'tests', '__tests__', 'admin', 'api', 'founder']);

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIR.has(name)) continue;
    const p = join(dir, name);
    const s = statSync(p);
    if (s.isDirectory()) yield* walk(p);
    else if (['.ts', '.tsx'].includes(extname(p)) && !p.endsWith('.test.ts') && !p.endsWith('.test.tsx')) yield p;
  }
}

// Keep a candidate only if it reads like member copy: has a letter, and (a capital letter OR sentence punctuation),
// and isn't a path / className / identifier / css / url.
function isMemberCopy(s) {
  const t = s.trim();
  if (t.length < 4 || !/[a-zA-Z]/.test(t)) return false;
  if (/^[.\/#]|https?:|@\/|\.(tsx?|css|svg|png|jpg|json)\b|\/[a-z]/.test(t)) return false;       // paths / urls / files
  if (/^[A-Z0-9_-]+$/.test(t)) return false;                                                       // ALL_CAPS tokens (RWR-W1, GOOD_CALL)
  if (/^[a-z][a-z0-9]*([ -][a-z0-9]+)*$/.test(t)) return false;                                    // classNames / lowercase tokens
  if (/[{}<>]|=>|\$\{?\w+\}|::|--[a-z]/.test(t) && !/[.?!]/.test(t) && !/ [A-Z]/.test(t)) return false; // codey w/o sentence feel
  if (!/[A-Z]/.test(t) && !/[.?!,;:]/.test(t) && !t.includes(' ')) return false;                   // bare lowercase word
  return true;
}

const seen = new Map(); // normalized string -> { text, first: 'file:line', count }
for (const file of INCLUDE.flatMap((d) => { try { return [...walk(join(ROOT, d))]; } catch { return []; } })) {
  const rel = file.slice(ROOT.length + 1);
  const lines = readFileSync(file, 'utf8').split('\n');
  lines.forEach((line, i) => {
    const cands = [];
    // quoted string literals: '...', "...", `...`
    for (const m of line.matchAll(/(['"`])((?:\\.|(?!\1).)*)\1/g)) cands.push(m[2]);
    // JSX text nodes: >text<
    for (const m of line.matchAll(/>\s*([^<>{}][^<>{}]*?)\s*</g)) cands.push(m[1]);
    for (const raw of cands) {
      const t = raw.replace(/\\'/g, "'").replace(/\\"/g, '"').trim();
      if (!isMemberCopy(t)) continue;
      const key = t.toLowerCase();
      if (seen.has(key)) seen.get(key).count++;
      else seen.set(key, { text: t, first: `${rel}:${i + 1}`, count: 1 });
    }
  });
}

const rows = [...seen.values()].sort((a, b) => a.text.localeCompare(b.text));

// A NAMED TERM / LABEL: short, no ending sentence-punctuation, and carries a proper-noun capital (a capital that isn't
// just the sentence-start) — i.e. "Good Call", "The Lifestyle Pilot", "Reclaim List", "the Athlete", "Field Guide".
// This is the high-signal sweep shortlist (the things that must match the glossary), vs. the full body-copy dump below.
function isTerm(t) {
  if (!/^["']?[A-Za-z]/.test(t)) return false;                                     // must start with a letter (drops ←, ▶, ·, {, (, commas)
  if (/\$\{|[←▶·⚑♡♥⬢◆●✓✗]|=>|\):|: (Set|Promise|Partial|Record|Db|string|number)\b/.test(t)) return false; // code/symbol fragments
  const words = t.split(/\s+/);
  if (words.length > 6 || /[.?!,;:]$/.test(t) || t.length > 48) return false;
  const capWords = words.filter((w) => /^[A-Z]/.test(w)).length;
  const midCap = words.slice(1).some((w) => /^[A-Z]/.test(w)); // a capital past the first word = a proper noun
  return capWords >= 2 || midCap;
}
const terms = rows.filter((r) => isTerm(r.text));

const fmt = (r) => `[${r.first}${r.count > 1 ? ` +${r.count - 1}` : ''}] ${r.text}`;
const out = [
  `# Member-facing string inventory — ${rows.length} strings (${terms.length} candidate terms)`,
  `# Generated by scripts/extract-member-strings.mjs. Heuristic (errs toward inclusion); verify via the file:line.`,
  `# Caveat: agent SYSTEM-PROMPT / tool-description prose lives in the same files as member copy and can't be fully`,
  `# separated mechanically — so SECTION 2 has some model-instruction noise. SECTION 1 (named terms) is the sweep list.`,
  '',
  `## SECTION 1 — Candidate terms & labels (${terms.length}) — the naming targets for the glossary`,
  '',
  ...terms.map(fmt),
  '',
  `## SECTION 2 — All member-facing strings (${rows.length}) — full body copy, for completeness`,
  '',
  ...rows.map(fmt),
].join('\n');
writeFileSync(join(ROOT, 'docs/member-facing-strings.txt'), out + '\n');
console.log(`Wrote docs/member-facing-strings.txt — ${terms.length} candidate terms, ${rows.length} total strings.`);
